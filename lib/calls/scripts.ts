    /** 응답 수집 프롬프트(어댑터에 넘기는 collect 라벨). */
    ask: "어떠세요?",
    /** 애매할 때 1회 재질문. */
    reask: "죄송해요, 잘 못 들었어요. 하셨으면 1번, 안 하셨으면 2번을 눌러주세요.",
